// Loads the study catalog (app.blocks, app.study_items) from content/, so the server can check a
// review, quiz answer or finished chapter before it earns points (database/schema/06_study.sql).
//   npm run db:content            writes it to the database in POSTGRES_URL_NON_POOLING (or DATABASE_URL)
//   npm run db:content -- --print prints the SQL instead
// Safe to run any time: items are added or updated, and items no longer in content/ are retired
// (records already made with them keep counting). Run it after every content change; the
// content-catalog workflow does on each push to the default branch.
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const content = join(root, "content");

/** Each content/{type}/block/{block}/{subject}/{file} that exists, as [block, subject, path]. */
function subjectFiles(type, file) {
  const base = join(content, type, "block");
  if (!existsSync(base)) return [];
  const found = [];
  for (const block of readdirSync(base).sort()) {
    const blockDir = join(base, block);
    for (const subject of readdirSync(blockDir).sort()) {
      const path = join(blockDir, subject, file);
      if (existsSync(path)) found.push([block, subject, path]);
    }
  }
  return found;
}

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

/** [kind, deck, item_id, block, answer] rows. */
export function catalog() {
  const rows = [];
  for (const [block, subject, path] of subjectFiles("flashcards", "deck.json")) {
    for (const card of readJson(path)) rows.push(["flashcard", `${block}/${subject}`, card.id, block, null]);
  }
  for (const [block, subject, path] of subjectFiles("occlusion", "notes.json")) {
    // One card per label: the app's card id is `${note.id}:${mask.id}` (src/lib/occlusion.ts).
    for (const note of readJson(path)) {
      for (const mask of note.masks ?? []) rows.push(["occlusion", `${block}/${subject}`, `${note.id}:${mask.id}`, block, null]);
    }
  }
  for (const [block, subject, path] of subjectFiles("quizzes", "bank.json")) {
    for (const question of readJson(path)) {
      if (!Number.isInteger(question.answer)) throw new Error(`${path}: ${question.id} has no answer index`);
      rows.push(["quiz", `${block}/${subject}`, question.id, block, question.answer]);
    }
  }
  for (const [block, subject, path] of subjectFiles("ebooks", "meta.json")) {
    for (const chapter of readJson(path).chapters ?? []) rows.push(["chapter", `${block}/${subject}`, chapter.id, block, null]);
  }
  const seen = new Set();
  for (const [kind, deck, id] of rows) {
    const key = `${kind} ${deck} ${id}`;
    if (seen.has(key)) throw new Error(`duplicate ${kind} id in ${deck}: ${id}`);
    seen.add(key);
  }
  return rows;
}

const literal = (value) => (value === null ? "null" : typeof value === "number" ? String(value) : `'${String(value).replace(/'/g, "''")}'`);

export function catalogSql(rows) {
  const blocks = [...new Set(rows.map((row) => row[3]))].sort();
  const values = rows.map((row) => `  (${row.map(literal).join(", ")})`).join(",\n");
  return `-- Generated by scripts/content-catalog.mjs from content/.
begin;
insert into app.blocks (id) values ${blocks.map((b) => `(${literal(b)})`).join(", ")} on conflict do nothing;
create temporary table incoming (kind app.study_kind, deck text, item_id text, block text, answer int) on commit drop;
${rows.length ? `insert into incoming (kind, deck, item_id, block, answer) values\n${values};` : ""}
insert into app.study_items (kind, deck, item_id, block, answer)
select kind, deck, item_id, block, answer from incoming
on conflict (kind, deck, item_id) do update
  set block = excluded.block, answer = excluded.answer, retired_at = null
  where (app.study_items.block, app.study_items.answer, app.study_items.retired_at)
        is distinct from (excluded.block, excluded.answer, null::timestamptz);
update app.study_items s set retired_at = now()
 where s.retired_at is null
   and not exists (select 1 from incoming i where i.kind = s.kind and i.deck = s.deck and i.item_id = s.item_id);
select kind, count(*) filter (where retired_at is null) as live, count(*) filter (where retired_at is not null) as retired
  from app.study_items group by kind order by kind;
commit;
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = catalogSql(catalog());
  if (process.argv.includes("--print")) {
    process.stdout.write(sql);
  } else {
    const url = process.env.POSTGRES_URL_NON_POOLING || process.env.DATABASE_URL;
    if (!url) {
      console.error("set POSTGRES_URL_NON_POOLING (or DATABASE_URL) to the database connection string, or pass --print");
      process.exit(1);
    }
    const run = spawnSync("psql", [url, "-q", "-v", "ON_ERROR_STOP=1"], { input: sql, stdio: ["pipe", "inherit", "inherit"] });
    if (run.error) {
      console.error(run.error.code === "ENOENT" ? "psql isn't installed (it comes with PostgreSQL's client tools)" : run.error.message);
      process.exit(1);
    }
    process.exit(run.status ?? 1);
  }
}
