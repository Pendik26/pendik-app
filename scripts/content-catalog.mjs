// Builds the study catalog from content/ into server/catalog.generated.ts, so the API can check a
// review, quiz answer or finished chapter before it earns points (server/study.ts).
//   npm run content:catalog           rewrites the file
//   npm run content:catalog -- --check fails when the file is out of date (the tests run this too)
// Run it after every content change and commit the result. Items no longer in content/ simply
// aren't in the catalog: records already made with them keep their points.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const content = join(root, "content");

/** Each content/{type}/block/{block}/{subject}/{file} that exists, as [block, subject, path]. */
function subjectFiles(type, file) {
  const base = join(content, type, "block");
  if (!existsSync(base)) return [];
  const found = [];
  for (const block of readdirSync(base).sort()) {
    const blockDir = join(base, block);
    for (const subject of readdirSync(blockDir).sort()) {
      const path = join(blockDir, subject, file);
      if (existsSync(path)) found.push([block, subject, path]);
    }
  }
  return found;
}

const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));

/** [kind, deck, item_id, block, answer] rows. */
export function catalog() {
  const rows = [];
  for (const [block, subject, path] of subjectFiles("flashcards", "deck.json")) {
    for (const card of readJson(path)) rows.push(["flashcard", `${block}/${subject}`, card.id, block, null]);
  }
  for (const [block, subject, path] of subjectFiles("occlusion", "notes.json")) {
    // One card per label: the app's card id is `${note.id}:${mask.id}` (src/lib/occlusion.ts).
    for (const note of readJson(path)) {
      for (const mask of note.masks ?? []) rows.push(["occlusion", `${block}/${subject}`, `${note.id}:${mask.id}`, block, null]);
    }
  }
  for (const [block, subject, path] of subjectFiles("quizzes", "bank.json")) {
    for (const question of readJson(path)) {
      if (!Number.isInteger(question.answer)) throw new Error(`${path}: ${question.id} has no answer index`);
      rows.push(["quiz", `${block}/${subject}`, question.id, block, question.answer]);
    }
  }
  for (const [block, subject, path] of subjectFiles("ebooks", "meta.json")) {
    for (const chapter of readJson(path).chapters ?? []) rows.push(["chapter", `${block}/${subject}`, chapter.id, block, null]);
  }
  const seen = new Set();
  for (const [kind, deck, id] of rows) {
    const key = `${kind} ${deck} ${id}`;
    if (seen.has(key)) throw new Error(`duplicate ${kind} id in ${deck}: ${id}`);
    seen.add(key);
  }
  return rows;
}

export const CATALOG_FILE = join(root, "server", "catalog.generated.ts");

/** The catalog as TypeScript: `kind|deck|item` keys, each with the quiz answer (null otherwise). */
export function catalogSource(rows) {
  const lines = rows.map(([kind, deck, id, , answer]) => `  ${JSON.stringify(`${kind}|${deck}|${id}`)}: ${answer === null ? "null" : answer},`);
  return `// Generated by scripts/content-catalog.mjs from content/. Don't edit: run npm run content:catalog.
export const CATALOG: Record<string, number | null> = {
${lines.join("\n")}
};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = catalogSource(catalog());
  if (process.argv.includes("--check")) {
    const current = existsSync(CATALOG_FILE) ? readFileSync(CATALOG_FILE, "utf8") : "";
    if (current !== source) {
      console.error("server/catalog.generated.ts is out of date: run npm run content:catalog");
      process.exit(1);
    }
  } else {
    writeFileSync(CATALOG_FILE, source);
  }
}
